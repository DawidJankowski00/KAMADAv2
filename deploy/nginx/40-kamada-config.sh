#!/bin/sh
# Runtime configuration of the Blazor app, written when the container starts so one image works for any environment
# (runs from nginx's /docker-entrypoint.d/):
#  - appsettings.json with the API address,
#  - security-headers.conf with a Content-Security-Policy that allows exactly that API and the inline scripts of
#    index.html (Blazor's import map), by hash.
set -eu

html=/usr/share/nginx/html
headers=/etc/nginx/kamada/security-headers.conf

if [ -n "${API_BASE_URL:-}" ]; then
    printf '{\n  "ApiBaseUrl": "%s"\n}\n' "$API_BASE_URL" > "$html/appsettings.json"
    # Remove stale pre-compressed copies produced by publish (gzip_static would serve them).
    rm -f "$html/appsettings.json.gz" "$html/appsettings.json.br"
    echo "KAMADA: ApiBaseUrl set to $API_BASE_URL"
fi

# Scheme, host and port only: CSP sources are origins.
api_origin=$(printf '%s' "${API_BASE_URL:-}" | sed -E 's#^(https?://[^/]+).*#\1#')

# SHA-256 of every inline <script> (no src attribute) in index.html, as CSP sources.
work=$(mktemp -d)
awk -v dir="$work" 'BEGIN { RS = "</script>"; n = 0 }
{
    start = index($0, "<script")
    if (start == 0) next
    tag_and_body = substr($0, start)
    tag_end = index(tag_and_body, ">")
    tag = substr(tag_and_body, 1, tag_end)
    if (tag ~ /[[:space:]]src=/) next
    file = dir "/script" n++
    printf "%s", substr(tag_and_body, tag_end + 1) > file
    close(file)
}' "$html/index.html"

script_hashes=""
for script in "$work"/script*; do
    [ -e "$script" ] || continue
    [ -s "$script" ] || continue
    hash=$(sha256sum "$script" | cut -d ' ' -f 1 | xxd -r -p | base64)
    script_hashes="$script_hashes 'sha256-$hash'"
done
rm -rf "$work"

csp="default-src 'self'"
csp="$csp; script-src 'self' 'wasm-unsafe-eval' https://cdn.jsdelivr.net$script_hashes"
csp="$csp; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com https://cdn.jsdelivr.net"
csp="$csp; font-src 'self' https://fonts.gstatic.com"
csp="$csp; img-src 'self' data: https://tile.openstreetmap.org https://cdn.jsdelivr.net"
csp="$csp; connect-src 'self' $api_origin"
csp="$csp; worker-src 'self'; manifest-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'"

{
    echo "# Generated by 40-kamada-config.sh at container start."
    echo 'add_header X-Content-Type-Options "nosniff" always;'
    echo 'add_header X-Frame-Options "DENY" always;'
    echo 'add_header Referrer-Policy "strict-origin-when-cross-origin" always;'
    echo 'add_header Permissions-Policy "camera=(), geolocation=(), payment=(), microphone=(self)" always;'
    echo "add_header Content-Security-Policy \"$csp\" always;"
} > "$headers"
echo "KAMADA: Content-Security-Policy allows the API at ${api_origin:-'self'} and $(echo "$script_hashes" | wc -w | tr -d ' ') inline script(s)"
